function obtenerEvento(id) {
    return eventosXalapa.find(evento => evento.id === id);
}

function fechaEventoLarga(evento) {
    const fecha = new Date(evento.fecha + "T12:00:00");
    return new Intl.DateTimeFormat("es-MX", {
        weekday: "long",
        day: "numeric",
        month: "long",
        year: "numeric"
    }).format(fecha);
}
function hoyXalapa(){const p=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Mexico_City',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(new Date());const v=t=>p.find(x=>x.type===t).value;return `${v('year')}-${v('month')}-${v('day')}`;}
function esPasado(e){return (e.fechaFin||e.fecha)<hoyXalapa();}
function proximosEventos(){return eventosXalapa.filter(e=>!esPasado(e)).sort((a,b)=>a.fecha.localeCompare(b.fecha));}
function anterioresEventos(){return eventosXalapa.filter(esPasado).sort((a,b)=>(b.fechaFin||b.fecha).localeCompare(a.fechaFin||a.fecha));}
function horarioEvento(e){return e.hora==='Horario por confirmar'?e.hora:e.hora+' hrs';}
function fechaVisible(e){return fechaEventoLarga(e)+(e.fechaFin&&e.fechaFin!==e.fecha?' – '+fechaEventoLarga({fecha:e.fechaFin}):'');}
